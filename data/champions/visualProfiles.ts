export function getVisualProfile(championId: string): ChampionVisualProfile {
  return (
    MAP.get(championId) ?? {
      championId,
      ...FALLBACK,
    }
  );
}

export function getVisualFrame(
  championId: string,
  context: keyof Omit<ChampionVisualProfile, "championId" | "verified">,
): ArtworkFrame {
  return getVisualProfile(championId)[context];
}

export function allVisualProfiles(): ChampionVisualProfile[] {
  return PROFILES;
}
